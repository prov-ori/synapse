function indicatorColor(ind, pH) {
  const r = ind.ranges.find(([a, b]) => pH >= a && pH < b) || ind.ranges[ind.ranges.length - 1];
  return { color: r[2], name: r[3] };
}
// Универсальный индикатор: от красного (pH 1) через зелёный (7) к фиолетовому (14)
function universalColor(pH) {
  const stops = [[0, [200, 20, 30]], [3, [240, 100, 30]], [5, [245, 200, 40]], [7, [60, 170, 70]], [9, [30, 120, 180]], [11, [50, 60, 170]], [14, [100, 30, 130]]];
  for (let i = 0; i < stops.length - 1; i++) {
    const [a, ca] = stops[i], [b, cb] = stops[i + 1];
    if (pH <= b) {
      const t = clamp((pH - a) / (b - a), 0, 1);
      const c = ca.map((v, k) => Math.round(v + (cb[k] - v) * t));
      return `rgb(${c.join(',')})`;
    }
  }
  return 'rgb(100,30,130)';
}

