// Атомные массы, округлённые «по-школьному» (как в справочных материалах ЕГЭ): Cl = 35,5, остальные — до целых
function schoolMass(sym) {
  if (sym === 'Cl') return 35.5;
  const e = EL[sym];
  if (!e) throw new Error('Неизвестный элемент: ' + sym);
  return Math.round(e.mass);
}

