// Возвращает массив [['1s', 2], ['2s', 2], …] в порядке номеров слоёв
function electronConfig(z, opts = {}) {
  const occ = {};
  let left = z;
  for (const orb of ORBITAL_ORDER) {
    if (left <= 0) break;
    const n = Math.min(left, ORBITAL_CAP[orb[1]]);
    occ[orb] = n;
    left -= n;
  }
  if (!opts.noExceptions && CONFIG_EXCEPTIONS[z]) {
    for (const [orb, d] of Object.entries(CONFIG_EXCEPTIONS[z])) occ[orb] = (occ[orb] || 0) + d;
  }
  const lOrder = 'spdf';
  return Object.entries(occ).filter(([, n]) => n > 0)
    .sort((a, b) => (a[0][0] - b[0][0]) || (lOrder.indexOf(a[0][1]) - lOrder.indexOf(b[0][1])));
}

function configString(z, opts = {}) {
  return electronConfig(z, opts).map(([o, n]) => o + supNum(n)).join(' ');
}

// Сокращённая запись с остовом благородного газа: [Ar] 3d⁶ 4s²
function configShort(z) {
  const nobles = [2, 10, 18, 36, 54, 86];
  const core = nobles.filter(n => n < z).pop();
  if (!core) return configString(z);
  const full = electronConfig(z);
  const coreSet = new Map(electronConfig(core));
  const rest = full.filter(([o, n]) => coreSet.get(o) !== n);
  return '[' + ELEMENTS[core - 1].sym + '] ' + rest.map(([o, n]) => o + supNum(n)).join(' ');
}

// Электроны по слоям (для модели Бора): [2, 8, 8, 2]
function shells(z) {
  const out = [];
  for (const [orb, n] of electronConfig(z)) {
    const k = +orb[0] - 1;
    out[k] = (out[k] || 0) + n;
  }
  return Array.from(out, x => x || 0);
}

